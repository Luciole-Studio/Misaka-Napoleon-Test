# ---------------------------------------------------------------- F1冲动模块
# F1 L251：胜利和约后18个月内启动新单边行动的概率≈0.7（基于1802–03与1810–11两窗口）。
# 本模块把"启动单边行动"与"该行动落在英国红线上"拆开：只有后者才拆毁和约。
# 红线定义按 B1b 六条件：索舰队/废汉诺威王朝/永久封闭英国市场/印度与地中海基地争夺。
def impulse_survival(cycles, redline_share, decay=0.93):
    """每18个月一个周期；年龄/健康衰退使冲动强度逐周期衰减（F1：1810–12已见体能衰退）。"""
    p = 1.0; r = redline_share
    for i in range(cycles):
        p *= (1.0 - 0.7 * r)
        r *= decay
    return p

IMPULSE = []
for rs in (0.30, 0.20, 0.15, 0.10, 0.08):
    IMPULSE.append((rs, round(impulse_survival(8, rs), 3), round(impulse_survival(14, rs), 3),
                    round(impulse_survival(22, rs), 3)))

